"""public/ad/vo/od_words.json -> src/oneday/words.ts (word start/end in film frames, 30 fps).

frame = cue + (aligned_time + calib - trim) * 30. Captions in src/oneday/Captions.tsx key every
word reveal to these frames, so changing a cue in build_oneday_audio.py means updating "cue" here.
"""
import json

FPS = 30
d = json.load(open("public/ad/vo/od_words.json"))
out = {}
for line, v in d.items():
    if line.startswith("_"):
        continue
    out[line] = [
        {"w": w, "s": round(v["cue"] + (s + v["calib"] - v["trim"]) * FPS, 1), "e": round(v["cue"] + (e + v["calib"] - v["trim"]) * FPS, 1)}
        for w, s, e in v["words"]
    ]
ts = "// generated by scripts/build_word_times.py from public/ad/vo/od_words.json — do not edit by hand\n"
ts += "export type Word = { w: string; s: number; e: number };\n"
ts += "export const WORDS: Record<string, Word[]> = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n"
open("src/oneday/words.ts", "w").write(ts)
for k, ws in out.items():
    print(k, " ".join(f"{x['w']}@{x['s']:.0f}" for x in ws))
