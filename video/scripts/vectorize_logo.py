"""Trace the authentic RESHAPE logo PNGs (extracted from the production site
index.html) into crisp SVG paths so the logo stays sharp at 1080x1920.
The shapes are traced, not redrawn: geometry comes straight from the source pixels."""
import sys, numpy as np, potrace, cv2
from PIL import Image

SCALE = 8

def alpha_mask(path):
    im = Image.open(path).convert("RGBA")
    a = np.asarray(im)[:, :, 3].astype(np.float32)
    return a

def upscale(mask, x0, x1, blur):
    sub = mask[:, x0:x1]
    big = cv2.resize(sub, (sub.shape[1] * SCALE, sub.shape[0] * SCALE), interpolation=cv2.INTER_CUBIC)
    # the source is a small, compressed PNG: blur away the pixel stair-steps before thresholding
    return cv2.GaussianBlur(big, (0, 0), SCALE * blur)

def polygon(mask, x0, x1):
    """The mark is built from straight edges, so fit it as a polygon (sharp corners, clean edges)."""
    big = upscale(mask, x0, x1, 0.5)
    cnts, _ = cv2.findContours((big > 127).astype(np.uint8), cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
    c = max(cnts, key=cv2.contourArea)
    poly = cv2.approxPolyDP(c, SCALE * 0.9, True)[:, 0, :]
    return "M" + "L".join(f"{x / SCALE + x0:.3f},{y / SCALE:.3f}" for x, y in poly) + "Z"

def trace(mask, x0, x1, alphamax, ox=0):
    big = upscale(mask, x0, x1, 0.55)
    bmp = potrace.Bitmap(big <= 127)  # potracer fills the False side
    plist = bmp.trace(turdsize=SCALE * SCALE * 2, alphamax=alphamax, opticurve=True, opttolerance=0.45)
    d = []
    f = lambda p: f"{(p.x / SCALE + x0 - ox):.3f},{(p.y / SCALE):.3f}"
    for curve in plist:
        d.append(f"M{f(curve.start_point)}")
        for seg in curve.segments:
            if seg.is_corner:
                d.append(f"L{f(seg.c)}L{f(seg.end_point)}")
            else:
                d.append(f"C{f(seg.c1)} {f(seg.c2)} {f(seg.end_point)}")
        d.append("Z")
    return "".join(d)

def bbox(mask):
    ys, xs = np.where(mask > 127)
    return xs.min(), xs.max() + 1, ys.min(), ys.max() + 1

src, outdir = sys.argv[1], sys.argv[2]
m = alpha_mask(src)
cols = (m > 127).any(axis=0)
# split mark | wordmark at the first empty column run after the mark
xs = np.where(cols)[0]
gaps = np.where(np.diff(xs) > 4)[0]
split = xs[gaps[0]] + 2
mark = polygon(m, 0, split)
word = trace(m, split, m.shape[1], alphamax=1.1)
H, W = m.shape
mx0, mx1, my0, my1 = bbox(m[:, :split])
wx0, wx1, wy0, wy1 = bbox(m)
open(f"{outdir}/reshape-logo.svg", "w").write(
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{wx0-1} {wy0-1} {wx1-wx0+2} {wy1-wy0+2}">'
    f'<path fill="currentColor" fill-rule="evenodd" d="{mark}"/>'
    f'<path fill="currentColor" fill-rule="evenodd" d="{word}"/></svg>\n')
open(f"{outdir}/reshape-mark.svg", "w").write(
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{mx0-1} {my0-1} {mx1-mx0+2} {my1-my0+2}">'
    f'<path fill="currentColor" fill-rule="evenodd" d="{mark}"/></svg>\n')
# also emit the paths as a TS module so the video can animate mark and wordmark separately
if len(sys.argv) > 3:
    open(sys.argv[3], "w").write(
        "// Generated by scripts/vectorize_logo.py from public/brand/source-logo-site.png - do not edit by hand.\n"
        f'export const MARK_PATH = "{mark}";\n'
        f'export const WORD_PATH = "{word}";\n'
        f"export const MARK_BOX = {{ x: {mx0 - 1}, y: {my0 - 1}, w: {mx1 - mx0 + 2}, h: {my1 - my0 + 2} }};\n"
        f"export const LOGO_BOX = {{ x: {wx0 - 1}, y: {wy0 - 1}, w: {wx1 - wx0 + 2}, h: {wy1 - wy0 + 2} }};\n"
    )
print("split", split, "mark bbox", (mx0, mx1, my0, my1), "full bbox", (wx0, wx1, wy0, wy1))
