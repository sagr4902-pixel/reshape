"""Write src/oneday/phoneTracks.ts: per-clip tracked screen quads (TL,TR,BR,BL in clip pixels,
one entry per 24 fps clip frame, null where the screen is not visible) for 16:9 ("h") and 9:16 ("v").
Captions use them to anchor callouts beside the phone and to keep text off the screen.
  python3 scripts/write_phone_tracks.py h:c01=<quads.json> h:c02=<...> v:c01=<...> ...
"""
import json
import sys

out = {"h": {}, "v": {}}
for arg in sys.argv[1:]:
    key, path = arg.split("=", 1)
    fmt, clip = key.split(":")
    d = json.load(open(path))
    out[fmt][clip] = {"w": d["w"], "h": d["h"], "fps": d["fps"],
                      "q": [None if q is None else [round(v, 1) for pt in q for v in pt] for q in d["quads"]]}
ts = "// generated by scripts/write_phone_tracks.py from the phone tracker output — do not edit by hand\n"
ts += "export type Track = { w: number; h: number; fps: number; q: (number[] | null)[] };\n"
ts += "export const PHONE_TRACKS: Record<'h' | 'v', Record<string, Track>> = " + json.dumps(out, separators=(",", ":")) + ";\n"
open("src/oneday/phoneTracks.ts", "w").write(ts)
print({k: list(v) for k, v in out.items()})
