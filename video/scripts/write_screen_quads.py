"""Write src/oneday/screenQuads.ts: the dusk phone's last tracked screen quad (16:9 and 9:16),
where the full-screen website stage starts its fly-out.
  python3 scripts/write_screen_quads.py <c12_quads_h.json> [<c12_quads_v.json>]
"""
import json
import sys


def last(p):
    d = json.load(open(p))
    q = [x for x in d["quads"] if x][-1]
    return {"w": d["w"], "h": d["h"], "quad": [[round(a, 1), round(b, 1)] for a, b in q]}


h = last(sys.argv[1])
v = last(sys.argv[2]) if len(sys.argv) > 2 else None
if v is None:  # until the vertical composite exists: centre a phone-sized quad in a 1080x1920 frame
    v = {"w": 1080, "h": 1920, "quad": [[300, 380], [780, 380], [780, 1420], [300, 1420]]}
out = "// generated by scripts/write_screen_quads.py from the phone tracker output\n"
out += "export const SCREEN_QUADS = " + json.dumps({"h": h, "v": v}) + " as const satisfies Record<'h' | 'v', { w: number; h: number; quad: number[][] }>;\n"
open("src/oneday/screenQuads.ts", "w").write(out)
print(out)
